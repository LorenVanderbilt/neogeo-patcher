"""The patcher's side of a game's release, for each game's tools/release.py to import:

    sys.path.insert(0, os.path.join(ROOT, "..", "neogeo-patcher", "tools"))
    import ngpatcher
    js = ngpatcher.patchdata_js("bjplus", data)        # data: release.py's dict (version, order, source, ...)
    ngpatcher.page_copy("bjplus", js, out_dir)          # a copy of the page for that game alone (itch.io, offline)
    ngpatcher.publish("bjplus", js)                     # games/bjplus/patchdata.js here, for the live page

The data's format is the engine's (patcher.js); this file only wraps and places it, so every game writes it alike.
"""
import json
import os
import re
import shutil

PATCHER = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGE_FILES = ["index.html", "patcher.js", "games.js"]


def patchdata_js(game_id, data):
    """games/<id>/patchdata.js's text: data, as module.exports under Node and window.PATCHDATA[<id>] in a page."""
    if not re.fullmatch(r"[a-z0-9-]+", game_id):
        raise ValueError("game id %r: lower-case letters, digits and - only" % game_id)
    return ("// Generated by %s's tools/release.py for %s - don't edit.\n"
            "(function (d) { if (typeof module !== \"undefined\") module.exports = d;\n"
            "  else (window.PATCHDATA = window.PATCHDATA || {})[%s] = d; })(%s);\n"
            % (game_id, data["version"], json.dumps(game_id), json.dumps(data)))


def publish(game_id, js):
    """Writes the live page's data for the game. Returns the path."""
    _known(game_id)
    path = os.path.join(PATCHER, "games", game_id, "patchdata.js")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(js)
    return path


def page_copy(game_id, js, dest):
    """dest/: the page for this game alone (its data loaded up front, so it needs no ?game=), as itch.io's HTML
    upload wants it (index.html at the root) and as it works opened from a file."""
    _known(game_id)
    os.makedirs(os.path.join(dest, "games", game_id), exist_ok=True)
    for n in PAGE_FILES:
        shutil.copy(os.path.join(PATCHER, n), os.path.join(dest, n))
    open(os.path.join(dest, "games", game_id, "patchdata.js"), "w").write(js)
    page = open(os.path.join(dest, "index.html")).read()
    tag = '<script src="games.js"></script>'
    assert page.count(tag) == 1, "index.html: the games.js script tag isn't there once"
    page = page.replace(tag, '<script src="games/%s/patchdata.js"></script>\n%s' % (game_id, tag))
    open(os.path.join(dest, "index.html"), "w").write(page)


def _known(game_id):
    if not re.search(r'\bid: "%s"' % re.escape(game_id), open(os.path.join(PATCHER, "games.js")).read()):
        raise SystemExit("%s isn't in %s - add its entry first" % (game_id, os.path.join(PATCHER, "games.js")))
